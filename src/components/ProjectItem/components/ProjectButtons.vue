<script>
export default {
  props: ["project", "userId", "mobileHoverElemId", "projectUrl"],

  emits: ["copy"],

  computed: {
    isDesktop() {
      return window.innerWidth > 500;
    },

    isAdminRole() {
      const ROLE = localStorage.getItem("ROLE");
      return ROLE === "ROLE_ADMIN";
    },

    isExecutorRole() {
      const ROLE = localStorage.getItem("ROLE");
      return ROLE === "ROLE_EXECUTOR";
    },

    user() {
      return JSON.parse(localStorage.getItem("user"));
    },
  },

  methods: {
    copy(project) {
      // const url = window.location.origin + "/project/" + project.id;
      const url = window.location.origin + this.projectUrl;

      navigator.clipboard.writeText(url).then(
        () => {
          this.$emit("copy", project.id);
          setTimeout(() => this.$emit("copy", null), 1000);
        },
        function (err) {
          console.error("Async: Could not copy text: ", err);
        }
      );
    },

    edit() {
      this.$emit("edit");
    },
  },
};
</script>

